/**
 * Opérateur chat (ADR-0043) : accès strictement limité aux conversations de
 * son périmètre. Aucun accès aux liens, prospects, fiches globales ou
 * administration.
 */
const OPERATEUR: readonly Action[] = [
  "conversations:list",
  "conversations:read",
  "conversations:intervene",
  "conversations:update_fields",
  "conversations:generate_fiche",
];

const MATRIX: Record<Role, readonly Action[]> = {
  admin: ACTIONS,
  marketeur: MARKETEUR,
  lecteur: READ_ONLY,
  operateur: OPERATEUR,
};

/** Le rôle `role` peut-il effectuer l'action `action` ? */
export function can(role: Role, action: Action): boolean {
  return MATRIX[role].includes(action);
}

/** Actions autorisées pour un rôle (utilisé par la navigation filtrée). */
export function actionsFor(role: Role): readonly Action[] {
  return MATRIX[role];
}
